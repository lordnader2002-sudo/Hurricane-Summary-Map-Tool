/*
 * Build the offline data bundles under offline/ from raw source downloads.
 *
 * Inputs (download these to a working directory first):
 *   Natural Earth 1:50m GeoJSON (public domain), from
 *   https://github.com/nvkelso/natural-earth-vector/tree/master/geojson :
 *     ne_50m_admin_0_countries.geojson
 *     ne_50m_admin_1_states_provinces_lines.geojson
 *     ne_50m_lakes.geojson
 *     ne_50m_populated_places_simple.geojson
 *   GeoNames US postal centroids (CC-BY 4.0), US.txt from
 *   https://download.geonames.org/export/zip/US.zip
 *   (mirrored at https://github.com/symerio/postal-codes-data)
 *
 * Usage:
 *   node scripts/build-offline-data.js <dir-with-ne-geojson> <path-to-US.txt>
 *
 * Outputs (window-global .js files so they load via <script> tags and work
 * from file:// where fetch() of local files is blocked):
 *   offline/basemap-countries.js   window.OFFLINE_BASEMAP.countries
 *   offline/basemap-states.js      window.OFFLINE_BASEMAP.states
 *   offline/basemap-lakes.js       window.OFFLINE_BASEMAP.lakes
 *   offline/basemap-cities.js      window.OFFLINE_BASEMAP.cities
 *   offline/zipcodes-us.js         window.OFFLINE_ZIP_US
 */
'use strict';

const fs = require('fs');
const path = require('path');

const [, , neDir, usTxt] = process.argv;
if (!neDir || !usTxt) {
  console.error('Usage: node scripts/build-offline-data.js <ne-geojson-dir> <US.txt>');
  process.exit(1);
}

const outDir = path.join(__dirname, '..', 'offline');
fs.mkdirSync(outDir, { recursive: true });

const COORD = 1e3; // 3 decimals ≈ 110 m — finer than the 1:50m source data

function round(n) { return Math.round(n * COORD) / COORD; }
function roundDeep(c) {
  return Array.isArray(c) ? c.map(roundDeep) : (typeof c === 'number' ? round(c) : c);
}

function readNe(name) {
  return JSON.parse(fs.readFileSync(path.join(neDir, name), 'utf8'));
}

function compactFC(gj, mapProps) {
  return {
    type: 'FeatureCollection',
    features: gj.features.map(f => ({
      type: 'Feature',
      geometry: { type: f.geometry.type, coordinates: roundDeep(f.geometry.coordinates) },
      properties: mapProps ? mapProps(f.properties) : {},
    })).filter(f => f.geometry.coordinates && f.geometry.coordinates.length),
  };
}

function write(name, globalExpr, obj) {
  const file = path.join(outDir, name);
  const js = '// Generated by scripts/build-offline-data.js — do not edit by hand.\n'
    + '// Sources: Natural Earth (public domain) / GeoNames (CC-BY 4.0).\n'
    + 'window.OFFLINE_BASEMAP = window.OFFLINE_BASEMAP || {};\n'
    + globalExpr + ' = ' + JSON.stringify(obj) + ';\n';
  fs.writeFileSync(file, js);
  console.log(name, Math.round(js.length / 1024) + ' KB');
}

// Countries: land fill + coastline/border stroke. Name kept for possible
// future hover use; everything else stripped (raw file has 168 properties).
const countries = compactFC(readNe('ne_50m_admin_0_countries.geojson'),
  p => ({ name: p.NAME || p.ADMIN || '' }));
write('basemap-countries.js', 'window.OFFLINE_BASEMAP.countries', countries);

// State/province boundary lines (US, CA, MX, BR, AU...): geometry only.
const states = compactFC(readNe('ne_50m_admin_1_states_provinces_lines.geojson'), () => ({}));
write('basemap-states.js', 'window.OFFLINE_BASEMAP.states', states);

// Large lakes only — small ones are noise at hurricane-map zooms.
const lakesRaw = readNe('ne_50m_lakes.geojson');
lakesRaw.features = lakesRaw.features.filter(f => (f.properties.scalerank ?? 9) <= 4);
write('basemap-lakes.js', 'window.OFFLINE_BASEMAP.lakes', compactFC(lakesRaw, () => ({})));

// Cities: importance rank (r; lower = bigger) drives zoom-based visibility.
const citiesRaw = readNe('ne_50m_populated_places_simple.geojson');
const cities = citiesRaw.features
  .filter(f => (f.properties.scalerank ?? 99) <= 8)
  .map(f => ({
    n: f.properties.name,
    r: f.properties.scalerank,
    c: [round(f.properties.longitude), round(f.properties.latitude)],
  }));
write('basemap-cities.js', 'window.OFFLINE_BASEMAP.cities', cities);

// US ZIP centroids: { "96815": [lat, lon], ... } at 4 decimals (~11 m).
const zip = {};
fs.readFileSync(usTxt, 'utf8').split('\n').forEach(line => {
  const cols = line.split('\t');
  if (cols.length < 11) return;
  const code = cols[1].trim();
  const lat = parseFloat(cols[9]);
  const lon = parseFloat(cols[10]);
  if (!/^\d{5}$/.test(code) || !isFinite(lat) || !isFinite(lon)) return;
  zip[code] = [Math.round(lat * 1e4) / 1e4, Math.round(lon * 1e4) / 1e4];
});
const zipJs = '// Generated by scripts/build-offline-data.js — do not edit by hand.\n'
  + '// Source: GeoNames postal codes (CC-BY 4.0), https://www.geonames.org\n'
  + 'window.OFFLINE_ZIP_US = ' + JSON.stringify(zip) + ';\n';
fs.writeFileSync(path.join(outDir, 'zipcodes-us.js'), zipJs);
console.log('zipcodes-us.js', Math.round(zipJs.length / 1024) + ' KB —', Object.keys(zip).length, 'ZIP codes');
